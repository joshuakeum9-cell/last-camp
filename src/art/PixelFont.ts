/** Every printable ASCII character, in texture order. */
const CHARS =
  ' !"#$%&\'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_`' +
  'abcdefghijklmnopqrstuvwxyz{|}~';

const TEXTURE_KEY = 'pixelfont-tex';

/** Build the font texture and register the bitmap font. Safe to call more than once. */
export function buildPixelFont(scene: Phaser.Scene): void {
  if (scene.cache.bitmapFont.has(FONT)) return;

  if (!scene.textures.exists(TEXTURE_KEY)) {
    const tex = scene.textures.createCanvas(TEXTURE_KEY, CHARS.length * CELL_W, CELL_H);
    if (!tex) throw new Error('[PixelFont] could not create the font texture');
    const ctx = tex.getContext();
    ctx.imageSmoothingEnabled = false;
    ctx.fillStyle = '#ffffff';

    for (let i = 0; i < CHARS.length; i++) {
      const rows = G[CHARS[i]] ?? blank;
      const ox = i * CELL_W;
      for (let y = 0; y < rows.length && y < GLYPH_H; y++) {
        const row = rows[y];
        for (let x = 0; x < row.length && x < GLYPH_W; x++) {
          if (row[x] === '#') ctx.fillRect(ox + x, y, 1, 1);
        }
      }
    }
    tex.refresh();
  }

  const data = Phaser.GameObjects.RetroFont.Parse(scene, {
    image: TEXTURE_KEY,
    width: CELL_W,
    height: CELL_H,
    chars: CHARS,
    charsPerRow: CHARS.length,
    'offset.x': 0,
    'offset.y': 0,
    'spacing.x': 0,
    'spacing.y': 0,
    lineSpacing: 2,
  });
  scene.cache.bitmapFont.add(FONT, data);
}

/** Pixel width of a string at a given scale, for centring and panel sizing. */
export function textWidth(str: string, scale = 1): number {
  const longest = str.split('\n').reduce((m, line) => Math.max(m, line.length), 0);
  return Math.max(0, longest * CELL_W - 1) * scale;
}

export function textHeight(str: string, scale = 1): number {
  const lines = str.split('\n').length;
  return (lines * CELL_H + (lines - 1) * 2) * scale;
}

/**
 * Break a string onto lines no wider than `maxChars`, without splitting words.
 * Used by notes, dialogue and tooltips.
 */
export function wrap(str: string, maxChars: number): string {
  const out: string[] = [];
  for (const paragraph of str.split('\n')) {
    let line = '';
    for (const word of paragraph.split(' ')) {
      if (line.length === 0) {
        line = word;
      } else if (line.length + 1 + word.length <= maxChars) {
        line += ' ' + word;
      } else {
        out.push(line);
        line = word;
      }
    }
    out.push(line);
  }
  return out.join('\n');
}
